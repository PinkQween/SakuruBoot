static const u8 RCON[11] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

/* ------------------------------------------------------------------ */
/* GF(2^8) multiplication                                              */
/* ------------------------------------------------------------------ */
static u8 xtime(u8 a) { return (a<<1)^((a>>7)?0x1b:0); }
static u8 gmul(u8 a,u8 b){
    u8 r=0,p=a;
    for(int i=0;i<8;i++){if(b&1)r^=p; p=xtime(p); b>>=1;}
    return r;
}

/* ------------------------------------------------------------------ */
/* Key schedule                                                        */
/* ------------------------------------------------------------------ */
static u32 sub_word(u32 w){
    return ((u32)SBOX[(w>>24)&0xff]<<24)|((u32)SBOX[(w>>16)&0xff]<<16)|
           ((u32)SBOX[(w>> 8)&0xff]<< 8)|((u32)SBOX[(w    )&0xff]);
}
static u32 rot_word(u32 w){return(w<<8)|(w>>24);}
static u32 bytes_to_word(const u8 *b){
    return ((u32)b[0]<<24)|((u32)b[1]<<16)|((u32)b[2]<<8)|(u32)b[3];
}

void aes_init_enc(AES_CTX *ctx, const u8 *key, int key_len) {
    int nk = key_len/4;
    ctx->nr = (nk==4)?10:14;
    int tot = (ctx->nr+1)*4;
    for(int i=0;i<nk;i++) ctx->rk[i]=bytes_to_word(key+i*4);
    for(int i=nk;i<tot;i++){
        u32 t=ctx->rk[i-1];
        if(i%nk==0) t=sub_word(rot_word(t))^((u32)RCON[i/nk]<<24);
        else if(nk>6&&i%nk==4) t=sub_word(t);
        ctx->rk[i]=ctx->rk[i-nk]^t;
    }
}

/* For decryption key schedule we derive the inverse mix-columns keys */
static u32 inv_mix_col(u32 w){
    u8 a=(u8)(w>>24),b=(u8)(w>>16),c=(u8)(w>>8),d=(u8)w;
    u8 r0=gmul(0x0e,a)^gmul(0x0b,b)^gmul(0x0d,c)^gmul(0x09,d);
    u8 r1=gmul(0x09,a)^gmul(0x0e,b)^gmul(0x0b,c)^gmul(0x0d,d);
    u8 r2=gmul(0x0d,a)^gmul(0x09,b)^gmul(0x0e,c)^gmul(0x0b,d);
    u8 r3=gmul(0x0b,a)^gmul(0x0d,b)^gmul(0x09,c)^gmul(0x0e,d);
    return((u32)r0<<24)|((u32)r1<<16)|((u32)r2<<8)|(u32)r3;
}

void aes_init_dec(AES_CTX *ctx, const u8 *key, int key_len) {
    aes_init_enc(ctx, key, key_len);
    /* Apply InvMixColumns to middle round keys (equivalent inverse cipher) */
    for(int i=4;i<ctx->nr*4;i++) ctx->rk[i]=inv_mix_col(ctx->rk[i]);
}

/* ------------------------------------------------------------------ */
/* Encrypt one block                                                   */
/* ------------------------------------------------------------------ */
static void add_rk(u8 s[16], const u32 *rk){
    for(int c=0;c<4;c++){
        s[c*4+0]^=(u8)(rk[c]>>24); s[c*4+1]^=(u8)(rk[c]>>16);
        s[c*4+2]^=(u8)(rk[c]>>8);  s[c*4+3]^=(u8)(rk[c]);
    }
}
static void sub_bytes(u8 s[16]){for(int i=0;i<16;i++) s[i]=SBOX[s[i]];}
static void shift_rows(u8 s[16]){
    u8 t;
    t=s[1]; s[1]=s[5]; s[5]=s[9]; s[9]=s[13]; s[13]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[15]; s[15]=s[11]; s[11]=s[7]; s[7]=s[3]; s[3]=t;
}
static void mix_columns(u8 s[16]){
    for(int c=0;c<4;c++){
        u8 a=s[c*4],b=s[c*4+1],cc=s[c*4+2],d=s[c*4+3];
        s[c*4  ]=xtime(a)^xtime(b)^b^cc^d;
        s[c*4+1]=a^xtime(b)^xtime(cc)^cc^d;
        s[c*4+2]=a^b^xtime(cc)^xtime(d)^d;
        s[c*4+3]=xtime(a)^a^b^cc^xtime(d);
    }
}

void aes_encrypt_block(const AES_CTX *ctx, const u8 in[16], u8 out[16]) {
    u8 s[16]; for(int i=0;i<16;i++) s[i]=in[i];
    /* Reinterpret as column-major (AES uses column-major state) */
    u8 state[16];
    for(int r=0;r<4;r++) for(int c=0;c<4;c++) state[c*4+r]=s[r*4+c];
    add_rk(state, ctx->rk);
    for(int rd=1;rd<=ctx->nr;rd++){
        sub_bytes(state);
        shift_rows(state);
        if(rd<ctx->nr) mix_columns(state);
        add_rk(state, ctx->rk+rd*4);
    }
    for(int r=0;r<4;r++) for(int c=0;c<4;c++) out[r*4+c]=state[c*4+r];
}

/* ------------------------------------------------------------------ */
/* Decrypt one block (equivalent inverse cipher)                       */
/* ------------------------------------------------------------------ */
static void inv_sub_bytes(u8 s[16]){for(int i=0;i<16;i++) s[i]=RSBOX[s[i]];}
static void inv_shift_rows(u8 s[16]){
    u8 t;
    t=s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[3]; s[3]=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=t;
}
static void inv_mix_columns(u8 s[16]){
    for(int c=0;c<4;c++){
        u8 a=s[c*4],b=s[c*4+1],cc=s[c*4+2],d=s[c*4+3];
        s[c*4  ]=gmul(0x0e,a)^gmul(0x0b,b)^gmul(0x0d,cc)^gmul(0x09,d);
        s[c*4+1]=gmul(0x09,a)^gmul(0x0e,b)^gmul(0x0b,cc)^gmul(0x0d,d);
        s[c*4+2]=gmul(0x0d,a)^gmul(0x09,b)^gmul(0x0e,cc)^gmul(0x0b,d);
        s[c*4+3]=gmul(0x0b,a)^gmul(0x0d,b)^gmul(0x09,cc)^gmul(0x0e,d);
    }
}

void aes_decrypt_block(const AES_CTX *ctx, const u8 in[16], u8 out[16]) {
    u8 state[16];
    for(int r=0;r<4;r++) for(int c=0;c<4;c++) state[c*4+r]=in[r*4+c];
    add_rk(state, ctx->rk + ctx->nr*4);
    for(int rd=ctx->nr-1;rd>=0;rd--){
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_rk(state, ctx->rk + rd*4);
        if(rd>0) inv_mix_columns(state);
    }
    for(int r=0;r<4;r++) for(int c=0;c<4;c++) out[r*4+c]=state[c*4+r];
}
